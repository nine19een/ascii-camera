const { chromium } = require(process.env.ASCII_AUDIT_PLAYWRIGHT || 'playwright')
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
fs.mkdirSync('.audit-backup',{recursive:true})
;(async () => {
  const browser = await chromium.launch({channel:process.env.ASCII_AUDIT_BROWSER || 'msedge',headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']})
  const context = await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true,permissions:['camera']})
  const page = await context.newPage()
  const errors=[], requests=[], downloads=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>requests.push({url:r.url(),method:r.method()}))
  await page.addInitScript(() => {
    window.auditStreams=[];window.auditGum=[]
    const original=navigator.mediaDevices.getUserMedia.bind(navigator.mediaDevices)
    navigator.mediaDevices.getUserMedia=async constraints=>{window.auditGum.push(constraints);const s=await original(constraints);window.auditStreams.push(s);return s}
    const create=URL.createObjectURL.bind(URL),revoke=URL.revokeObjectURL.bind(URL)
    window.auditUrls=new Set()
    URL.createObjectURL=b=>{const u=create(b);window.auditUrls.add(u);return u}
    URL.revokeObjectURL=u=>{window.auditUrls.delete(u);revoke(u)}
  })
  const download=async (label,action)=>{
    const pending=page.waitForEvent('download',{timeout:30000})
    await action()
    const d=await pending
    const file=path.resolve('.audit-backup',label+path.extname(d.suggestedFilename()))
    await d.saveAs(file);downloads.push(file)
    console.log('download',label,fs.statSync(file).size)
  }
  const shutter=page.locator('button.shutter')
  await page.goto('http://127.0.0.1:4173/')
  await page.waitForFunction(()=>document.querySelector('.ascii-canvas')?.width>100)
  assert.equal(await page.evaluate(()=>window.auditGum.length),0)
  assert.equal(await page.locator('.demo-video').count(),1)
  assert.equal(await page.locator('canvas.preset-canvas').count(),6)
  await page.getByRole('button',{name:'EN',exact:true}).click()
  await download('smoke-png',()=>shutter.click())
  await page.locator('[data-format="video"][role="radio"]').click()
  await shutter.click()
  await page.waitForTimeout(600)
  await page.locator('button[data-preset="neon-purple"]').click()
  await page.getByRole('button',{name:'Compare',exact:true}).click()
  await page.locator('[role="slider"]').press('ArrowRight')
  await page.getByRole('button',{name:'Adjust',exact:true}).click()
  await page.locator('input[type="range"]').first().fill('180')
  await page.locator('input[name="charset"][value="blocks"]').check()
  await page.locator('input[name="charset"][value="binary"]').check()
  assert.equal(await page.locator('input[name="video-format"]').first().isDisabled(),true)
  await page.getByRole('button',{name:'Close adjust',exact:false}).click()
  await page.getByRole('button',{name:'Freeze',exact:true}).click()
  await page.getByRole('button',{name:'Fullscreen',exact:true}).click()
  await page.waitForFunction(()=>document.fullscreenElement!==null)
  await page.locator('.fullscreen-exit').click()
  await page.getByRole('button',{name:'中文',exact:true}).click()
  await page.locator('.ctl-left button').first().click()
  await page.waitForFunction(()=>document.querySelector('video.source-video:not(.demo-video)').srcObject?.active)
  await page.waitForTimeout(700)
  await page.locator('.ctl-left button').first().click()
  await page.waitForTimeout(600)
  await download('smoke-mp4',()=>shutter.click())
  assert.equal(await page.locator('.export-result .export-meta').count(),1)
  await page.waitForFunction(()=>document.querySelector('.capture').dataset.state==='idle')
  // A second MP4 tests consecutive recording and recorder cleanup.
  await shutter.click();await page.waitForTimeout(1300)
  await download('smoke-mp4-repeat',()=>shutter.click())
  assert.equal(await page.locator('.export-result .export-meta').count(),1)
  await page.waitForFunction(()=>document.querySelector('.capture').dataset.state==='idle')
  await page.getByRole('button',{name:'EN',exact:true}).click()
  await page.getByRole('button',{name:'Adjust',exact:true}).click()
  await page.locator('input[name="video-format"][value="webm"]').check()
  await page.getByRole('button',{name:'Close adjust',exact:false}).click()
  await shutter.click();await page.waitForTimeout(3200)
  await page.locator('button[data-preset="natural-color"]').click()
  await page.setViewportSize({width:1100,height:800})
  await page.waitForTimeout(700)
  await download('smoke-webm',()=>shutter.click())
  assert.equal(await page.locator('.export-result .export-meta').count(),1)
  await page.waitForFunction(()=>document.querySelector('.capture').dataset.state==='idle')
  await page.locator('[data-format="gif"][role="radio"]').click()
  await shutter.click();await page.waitForTimeout(1600)
  await download('smoke-gif',()=>shutter.click())
  await page.waitForFunction(()=>document.querySelector('.capture').dataset.state==='idle')
  await shutter.click();await page.waitForTimeout(300)
  await page.locator('.capture-cancel').click()
  await page.waitForFunction(()=>document.querySelector('.capture').dataset.state==='idle')
  await page.screenshot({path:'.audit-backup/smoke-desktop.png'})
  await page.setViewportSize({width:390,height:844})
  await page.waitForFunction(()=>document.querySelector('.app').dataset.layout==='compact')
  await page.getByRole('button',{name:'Adjust',exact:true}).click()
  await page.getByRole('tab',{name:'Glyphs',exact:true}).click()
  await page.screenshot({path:'.audit-backup/smoke-mobile.png'})
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await page.setViewportSize({width:844,height:390})
  await page.waitForFunction(()=>document.querySelector('.app').dataset.layout==='landscape')
  const liveTracks=await page.evaluate(()=>window.auditStreams.flatMap(s=>s.getTracks()).filter(t=>t.readyState==='live').length)
  assert.equal(liveTracks,0)
  const result={browser:browser.version(),downloads,errors,requests,liveTracks,gum:await page.evaluate(()=>window.auditGum),urlsBeforePagehide:await page.evaluate(()=>window.auditUrls.size)}
  await page.evaluate(()=>window.dispatchEvent(new PageTransitionEvent('pagehide')))
  result.urlsAfterPagehide=await page.evaluate(()=>window.auditUrls.size)
  assert.equal(result.urlsAfterPagehide,0)
  assert.deepEqual(errors,[])
  assert(requests.every(r=>r.url.startsWith('http://127.0.0.1:4173/')||r.url.startsWith('blob:')))
  fs.writeFileSync('.audit-backup/browser-results.json',JSON.stringify(result,null,2))
  console.log(JSON.stringify(result,null,2))
  await browser.close()
})().catch(e=>{console.error(e);process.exit(1)})

